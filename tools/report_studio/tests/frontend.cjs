const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const source=fs.readFileSync(require('node:path').join(__dirname,'../static/visuals.js'),'utf8');
const context={window:{}};
vm.runInNewContext(source,context);
const scalar=context.window.ReportVisuals.scalar;
assert.equal(scalar('5.9%','%'),5.9);
assert.equal(scalar('≤5.0%','%'),5);
assert.equal(scalar('约65天','天'),65);
assert.equal(scalar('-3,200','元'),-3200);
assert.equal(scalar('未单列','亿元'),null);
assert.equal(scalar('10–20','亿元'),null);
assert.equal(scalar('60天 / 90天','天'),null);
console.log('Frontend scalar checks passed');
const splitRoadmap=context.window.ReportVisuals.splitRoadmap;
const split=splitRoadmap({periods:['2026H2','2027','2027H1','2027H2'],milestones:[{period:'2027'},{period:'2027H1'}]});
assert.equal(JSON.stringify(split.periods),JSON.stringify(['2026H2','2027H1','2027H2']));
assert.equal(split.undated.length,1);
assert.equal(split.dated.length,1);
assert.equal(splitRoadmap({periods:['2026','2027'],milestones:[{period:'2027'}]}).dated.length,1);
console.log('Roadmap precision checks passed');
const monthly=context.window.ReportVisuals.lineLayout(['2026-01','2026-02','2026-04','2026-05','2026-06'].map(label=>({label})));
assert.equal(JSON.stringify(monthly.positions),JSON.stringify([0,.2,.6,.8,1]));
assert.equal(JSON.stringify(monthly.segments),JSON.stringify([[0,1],[2,3,4]]));
assert.equal(context.window.ReportVisuals.lineLayout([{label:'甲'},{label:'乙'}]).temporal,false);
console.log('Missing-month line checks passed');
const compare=context.window.ReportVisuals.compareCell;
const baseline={value:'10',comparable:true};
assert.equal(compare({value:'12'},baseline,{unit:'元',direction:'higher'}),'better');
assert.equal(compare({value:'-3'},baseline,{unit:'元',direction:'higher'}),'worse');
assert.equal(compare({value:'8'},baseline,{unit:'天',direction:'lower'}),'better');
assert.equal(compare({value:'12',comparable:false},baseline,{unit:'元',direction:'higher'}),'');
assert.equal(compare({value:'12'},baseline,{unit:'元',direction:'none'}),'');
assert.equal(compare({value:'≤12'},baseline,{unit:'元',direction:'higher'}),'');
assert.equal(compare({value:'—'},baseline,{unit:'元',direction:'higher'}),'');
assert.equal(compare({value:'12'},null,{unit:'元',direction:'higher'}),'');
assert.equal(context.window.ReportVisuals.sparseRoadmap(Array.from({length:8},(_,i)=>({lane:'工程'+i}))),true);
assert.equal(context.window.ReportVisuals.sparseRoadmap([{lane:'营销'},{lane:'渠道'},{lane:'渠道'}]),false);
console.log('Comparable-cell and sparse-roadmap checks passed');
assert.equal(JSON.stringify(context.window.ReportVisuals.plotBounds([2.77,7.87])),JSON.stringify([0,10]));
assert.equal(JSON.stringify(context.window.ReportVisuals.plotBounds([0,0])),JSON.stringify([0,1]));
assert.equal(JSON.stringify(context.window.ReportVisuals.plotBounds([-3,-2])),JSON.stringify([-5,0]));
console.log('Scatter domain checks passed');
const contextFacts=context.window.ReportVisuals.contextFacts;
const facts=contextFacts({visuals:[{kind:'scatter',x_label:'接管',x_unit:'次',y_label:'评分',y_unit:'分',source_ids:['S01'],points:[{label:'主体',x:5.86,y:4.79,quote:'原文',source_ids:[],emphasis:true}]}]});
assert.equal(facts[0].value,'4.79 分');
assert.equal(facts[1].value,'5.86 次');
assert.equal(JSON.stringify(facts[0].source_ids),JSON.stringify(['S01']));
assert.equal(facts[1].quote,'原文');
assert.equal(contextFacts({visuals:[{kind:'flow',steps:['甲','乙']}]}).length,0);
assert.equal(contextFacts({visuals:[],chart:{kind:'line',unit:'元',source_ids:[],points:[{label:'2025',value:1,quote:'甲'},{label:'2026',value:2,quote:'乙'}]}})[1].value,'2 元');
console.log('Section context facts checks passed');
const comparisonFacts=contextFacts({visuals:[{kind:'comparison',after_label:'2025-04',unit:'%',source_ids:['S01'],rows:[{label:'价格',before:{value:2.6,quote:'之前'},after:{value:2.1,quote:'之后',source_ids:['S02']}}]}]});
assert.equal(comparisonFacts[0].value,'2.1 %');
assert.equal(comparisonFacts[0].label,'价格 · 2025-04');
assert.equal(comparisonFacts[0].quote,'之后');
assert.equal(JSON.stringify(comparisonFacts[0].source_ids),JSON.stringify(['S02']));
assert.equal(context.window.ReportVisuals.displayPeriod('June 2022'),'2022年6月');
assert.equal(context.window.ReportVisuals.displayPeriod('2025H1'),'2025H1');
assert.equal(context.window.ReportVisuals.displayPeriod('Unknown 2025'),'Unknown 2025');
console.log('Observed comparison and date presentation checks passed');
assert.equal(context.window.ReportVisuals.withUnit('18.37%','%'),'18.37%');
assert.equal(context.window.ReportVisuals.withUnit('24.65','亿元'),'24.65 亿元');
assert.equal(context.window.ReportVisuals.withUnit('增长2.2%','各格注明'),'增长2.2%');
console.log('Unit presentation checks passed');
assert.equal(context.window.ReportVisuals.columnTitle({label:'材料原句'},[{cells:[{value:'价格缓和',quote:'Inflation has eased.'}]}],0),'材料要点');
assert.equal(context.window.ReportVisuals.columnTitle({label:'材料原句'},[{cells:[{value:'Inflation has eased.',quote:'Inflation has eased.'}]}],0),'材料原句');
console.log('Quoted versus paraphrased table labels passed');
vm.runInNewContext(fs.readFileSync(require('node:path').join(__dirname,'../static/series.js'),'utf8'),context);
const series=context.window.ReportSeries;
const temporal=context.window.ReportVisuals.lineLayout(['2025-01','2025-02','2025-03','2025-05','2025-06'].map(label=>({label})));
assert.equal(JSON.stringify(series.segments([{value:1},null,{value:3},{value:4},{value:5}],temporal)),JSON.stringify([[0],[2],[3,4]]));
assert.equal(JSON.stringify(series.domain({series:[{points:[{value:-2},null]},{points:[{value:0},{value:4}]}]})),JSON.stringify([-3,5]));
assert.equal(series.tick(0.30000000000000004),'0.3');
assert.equal(series.tick(1234.56789),'1234.57');
assert.equal(series.displayValue(65.8,'%',true),'+65.8');
assert.equal(series.displayValue(65.8,'%'),'65.8','positive shares must not acquire growth-like signs');
assert.equal(series.displayValue(-4.5,'%'),'-4.5');
assert.equal(series.displayValue(12,'万辆'),'12');
assert.equal(JSON.stringify(series.scaleTicks(-50,150)),JSON.stringify([{value:-50,position:0},{value:0,position:25},{value:150,position:100}]));
assert.equal(JSON.stringify(series.scaleTicks(0,100)),JSON.stringify([{value:0,position:0},{value:100,position:100}]));
const multiFacts=contextFacts({visuals:[{kind:'multiseries',unit:'%',source_ids:['S01'],series:[{label:'总体',points:[{label:'2024',value:2.6,quote:'a'},{label:'2025',value:2.1,quote:'b'}]},{label:'核心',points:[{label:'2024',value:2.9,quote:'c'},null]}]}]});
assert.equal(multiFacts[1].label,'核心 · 2024');
assert.equal(multiFacts[1].value,'2.9 %');
console.log('Multi-series gaps, signed domain and context provenance passed');
vm.runInNewContext(fs.readFileSync(require('node:path').join(__dirname,'../static/story.js'),'utf8'),context);
const story=context.window.ReportStory;
assert.equal(story.activeSection([200,800,1400],160),0);
assert.equal(story.activeSection([-900,-100,500],160),1);
assert.equal(story.activeSection([-1500,-900,-300],160),2);
const scene={objects:[{id:'a',x:200,y:140},{id:'b',x:800,y:410}]};
const before=JSON.stringify(scene);
const gathered=story.positions(scene,{composition:'gather',focus:['a']});
const unfolded=story.positions(scene,{composition:'unfold',focus:['a']});
assert.equal(gathered.a.y,126);
assert.ok(unfolded.a.x<gathered.a.x);
assert.equal(JSON.stringify(scene),before);
console.log('Narrative reading boundaries and immutable scene layout passed');
const frame=story.focusFrame(gathered,['a']).split(' ').map(Number);
assert.equal(frame[2]/frame[3],1000/620);
assert.ok(frame[0]<gathered.a.x-80&&frame[0]+frame[2]>gathered.a.x+80);
const editorial=story.editorialPositions(scene,{focus:['b'],composition:'unfold'},'narrative');
assert.equal(editorial.b.x,500);
assert.equal(editorial.b.y,265);
assert.equal(JSON.stringify(scene),before);
const assembly={id:'cover',dx:12,dy:-8,angle:5};
const actionBeat={actions:[{object_id:'a',group:'cover',effect:'reveal'}]};
assert.equal(story.assemblyState({id:'a'},assembly,actionBeat,'narrative').transform,'translate(12px,-8px) rotate(5deg)');
assert.equal(story.assemblyState({id:'a'},assembly,actionBeat,'blueprint').effect,'none');
assert.equal(story.assemblyState({id:'b'},assembly,actionBeat,'narrative').transform,'translate(0px,0px) rotate(0deg)');
assert.equal(story.assemblyState({id:'b'},assembly,actionBeat,'structure').transform,'translate(12px,-8px) rotate(5deg)');
console.log('Editorial framing and named assembly poses preserve scene data');
const clustered=[279,278,277];
const placed=series.labelPositions(clustered);
assert.deepEqual(clustered,[279,278,277]);
assert.equal(placed[0]-placed[1],18);
assert.equal(placed[1]-placed[2],18);
assert.ok(Math.max(...placed)<=290&&Math.min(...placed)>=32);
assert.equal(JSON.stringify(series.labelPositions([150,32,70])),JSON.stringify([150,32,70]));
console.log('Direct endpoint labels avoid collisions without moving data');
