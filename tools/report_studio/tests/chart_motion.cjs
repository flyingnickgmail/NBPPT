const eventHandlers={},mediaHandlers=[];let observed=null,animations=0,finishes=0,cancels=0;
const media={matches:false,addEventListener:(name,handler)=>mediaHandlers.push(handler),removeEventListener:()=>{}};
class Observer{constructor(callback){this.callback=callback;}observe(target){observed=target;}unobserve(){}disconnect(){}}
const animated=node(['bar-fill']);animated.animate=()=>{animations++;return {finished:new Promise(()=>{}),finish(){finishes++;},cancel(){cancels++;}};};
const chart={dataset:{},querySelectorAll:()=>[animated]};
const liveContext={window:{},matchMedia:()=>media,IntersectionObserver:Observer,addEventListener:(name,handler)=>{eventHandlers[name]=handler;},removeEventListener:()=>{}};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'../static/chart_motion.js'),'utf8'),liveContext);
const controller=liveContext.window.ReportChartMotion.mount({querySelectorAll:()=>[chart]});
assert.equal(observed,chart);controller.replay();assert.equal(animations,1);
media.matches=true;mediaHandlers[0]({matches:true});assert.equal(finishes,1);assert.equal(cancels,1);controller.replay();assert.equal(animations,1,'replay must respect a live reduced-motion preference');
media.matches=false;mediaHandlers[0]({matches:false});controller.replay();assert.equal(animations,2);
eventHandlers.beforeprint();controller.replay();assert.equal(animations,2,'printing must stay static');eventHandlers.afterprint();controller.replay();assert.equal(animations,3);
controller.disconnect();
console.log('Runtime reduced-motion and print transitions stop and suppress animation');
